// Keep Premiere on the exact same alignment rules as the website, without a
// second manually maintained implementation or a server release dependency.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const source = await readFile(new URL('../src/wordAlignment.js', import.meta.url), 'utf8');
const names = [...source.matchAll(/^export (?:function|const) (\w+)/gm)].map(match => match[1]);
const output = `// Generated by scripts/build-bridge-alignment.mjs; edit src/wordAlignment.js.\n// Source SHA256: ${createHash('sha256').update(source).digest('hex')}\n${source.replace(/^export /gm, '')}\nmodule.exports = { ${names.join(', ')} };\n`;
await writeFile(new URL('../premiere-bridge/word-alignment.js', import.meta.url), output);
